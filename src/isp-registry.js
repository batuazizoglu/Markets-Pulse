export function companyCoverage(sources, products) {
  return ISP_COMPANIES.map(c => {
    const matched=sources.filter(s=>(s.company_ids||[]).includes(c.id));
    const rows=products.filter(p=>(p.company_ids||[]).includes(c.id));
    const current=rows.filter(p=>!p.stale);
    const status=!c.website?'website_unverified':!matched.length?'source_needed':
      matched.some(s=>s.status==='ok'&&s.parsed_count>0)?(matched.every(s=>s.status==='ok')?'tracked':'partial'):
      rows.length?'stale':matched.some(s=>s.status==='discovery')?'discovery':
      matched.every(s=>s.status==='pending')?'pending':'unavailable';
    return {...c,brands:[...new Set([c.brand,...matched.map(s=>s.provider)])],
      status,products:rows.length,current_products:current.length,priced_products:current.filter(p=>p.effective_monthly_try>0).length,
      sources:matched.map(s=>({slug:s.slug,name:s.name,url:s.url,status:s.status,error:s.error}))};
  });
}

export function socialDirectory(sources) {
  const brands=new Map(ISP_COMPANIES.map(c=>[c.brand,{brand:c.brand,website:c.website,company_ids:[c.id]}]));
  for(const s of sources) {
    const old=brands.get(s.provider);
    brands.set(s.provider,{brand:s.provider,website:old?.website||s.url,company_ids:[...new Set([...(old?.company_ids||[]),...(s.company_ids||[])])]});
  }
  // Advertising-only brands (for example GNÇ) do not create ISP companies or products.
  for(const brand of Object.keys(ISP_SOCIALS))if(!brands.has(brand))brands.set(brand,{brand,website:null,company_ids:[]});
  return [...brands.values()].map(b=>{
    const social={...(ISP_SOCIALS[b.brand]||{})};
    for(const s of sources.filter(s=>s.provider===b.brand))for(const link of s.meta?.social_links||[]){
      if(!social[link.platform])social[link.platform]=link.url;
    }
    return {...b,...social,ad_library_url:adLibraryUrl({...b,...social}),
      ad_library_type:adLibraryUrl(social,{allowKeyword:false})?'verified_page':'brand_search',
      automatic_status:'connection_required',visual_analysis_url:'/api/ad-visuals'};
  }).sort((a,b)=>a.brand.localeCompare(b.brand,'tr'));
}
